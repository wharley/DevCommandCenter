// Writes src/theme/tailwind.rs from the Tailwind palette the desktop uses
// (node_modules/tailwindcss/theme.css). Run from the repo root:
// node apps/native/scripts/gen-tailwind.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const FAMILIES = [
	"slate", "neutral", "red", "orange", "amber", "yellow", "lime", "green", "emerald",
	"cyan", "sky", "blue", "indigo", "violet", "fuchsia", "pink", "rose",
];
const here = dirname(fileURLToPath(import.meta.url));
const css = readFileSync(join(here, "../../../node_modules/tailwindcss/theme.css"), "utf8");
const version = JSON.parse(
	readFileSync(join(here, "../../../node_modules/tailwindcss/package.json"), "utf8"),
).version;
const pattern = /--color-([a-z]+)-(\d+): oklch\(([\d.]+)% ([\d.]+) ([\d.]+)\);/g;
const lines = [];
const float = (value) => {
	const text = String(Number(Number(value).toFixed(4)));
	return text.includes(".") ? text : `${text}.0`;
};
for (const [, family, shade, l, c, h] of css.matchAll(pattern)) {
	if (!FAMILIES.includes(family)) continue;
	const name = `${family.toUpperCase()}_${shade}`;
	lines.push(`pub const ${name}: Oklch = Oklch(${float(Number(l) / 100)}, ${float(c)}, ${float(h)});`);
}
const rust = `//! Tailwind ${version} palette colors the desktop's classes use
//! (\`bg-amber-500\`, \`text-sky-700\`…). Generated by
//! \`scripts/gen-tailwind.mjs\`; do not edit by hand.

use super::color::oklch;
use gpui::Hsla;

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Oklch(pub f32, pub f32, pub f32);

impl Oklch {
    pub fn hsla(self) -> Hsla {
        oklch(self.0, self.1, self.2)
    }

    /// \`bg-amber-500/12\`
    pub fn alpha(self, alpha: f32) -> Hsla {
        self.hsla().opacity(alpha)
    }
}

${lines.join("\n")}
`;
writeFileSync(join(here, "../src/theme/tailwind.rs"), rust);
console.log(`wrote ${lines.length} colors`);
